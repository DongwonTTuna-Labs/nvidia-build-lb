pub(super) fn transcription_probe_wav() -> Result<Vec<u8>, base64::DecodeError> {
    base64::engine::general_purpose::STANDARD.decode(TRANSCRIPTION_PROBE_WAV_BASE64)
}

pub(super) fn transcription_probe_matches(body: &[u8]) -> bool {
    serde_json::from_slice::<serde_json::Value>(body)
        .ok()
        .and_then(|value| value.get("text")?.as_str().map(str::to_owned))
        .is_some_and(|text| transcription_text_matches(&text))
}

pub(super) fn transcription_text_matches(text: &str) -> bool {
    text.split(|character: char| !character.is_alphanumeric())
        .any(|token| token.eq_ignore_ascii_case(TRANSCRIPTION_PROBE_EXPECTED_TOKEN))
}
